"""Generate the Python client in ``src/contracts/planner_client`` from the OpenAPI snapshot.

``models.py`` holds the pydantic models (written by datamodel-code-generator) and ``api.py`` one
typed method per ``operationId``. Run it after every change of ``src/contracts/openapi.json``::

    uv run planner-api export-openapi src/contracts/openapi.json
    uv run python scripts/generate_client.py

``--check`` regenerates into a temporary directory and fails when the committed files differ.
"""

from __future__ import annotations

import argparse
import json
import keyword
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "src" / "contracts" / "openapi.json"
PACKAGE = ROOT / "src" / "contracts" / "planner_client"
METHODS = ("get", "post", "put", "patch", "delete")

HEADER = '''"""{what}

Generated by scripts/generate_client.py from src/contracts/openapi.json. Do not edit.
"""
'''


def snake(name: str) -> str:
    text = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()
    text = re.sub(r"[^a-z0-9_]", "_", text)
    return f"{text}_" if keyword.iskeyword(text) else text


def generate_models(spec: Path, output: Path) -> None:
    subprocess.run(
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(spec),
            "--input-file-type",
            "openapi",
            "--output",
            str(output),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--snake-case-field",
            "--allow-population-by-field-name",
            "--strict-nullable",
            "--use-annotated",
            "--use-standard-collections",
            "--use-union-operator",
            "--field-constraints",
            "--reuse-model",
            "--deserialize-default-values",
            "enum",
            "--target-python-version",
            "3.12",
            "--disable-timestamp",
            "--formatters",
            "black",
            "isort",
        ],
        check=True,
    )


def class_name(schema_name: str) -> str:
    """Name the model generator gives a schema: ``Page_TeamOut_`` becomes ``PageTeamOut``."""
    return "".join(part[:1].upper() + part[1:] for part in schema_name.split("_") if part)


def schema_name(schema: dict[str, Any]) -> str | None:
    ref = schema.get("$ref")
    return class_name(ref.rsplit("/", 1)[-1]) if ref else None


def scalar_type(schema: dict[str, Any]) -> str:
    """Python type of a parameter schema."""
    if "anyOf" in schema:
        branches = [b for b in schema["anyOf"] if b.get("type") != "null"]
        return scalar_type(branches[0]) if len(branches) == 1 else "str"
    kind, fmt = schema.get("type"), schema.get("format")
    if kind == "integer":
        return "int"
    if kind == "number":
        return "float"
    if kind == "boolean":
        return "bool"
    if kind == "array":
        return f"list[{scalar_type(schema.get('items', {}))}]"
    if fmt == "date":
        return "date"
    if fmt == "date-time":
        return "datetime"
    return "str"


class Operation:
    def __init__(self, method: str, path: str, data: dict[str, Any]) -> None:
        self.method = method.upper()
        self.path = path
        self.data = data
        self.id: str = data["operationId"]

    def parameters(self, where: str) -> list[dict[str, Any]]:
        return [p for p in self.data.get("parameters", []) if p["in"] == where]

    @property
    def csv_body(self) -> bool:
        content = self.data.get("requestBody", {}).get("content", {})
        return "text/csv" in content and "application/json" not in content

    @property
    def csv_response(self) -> bool:
        for status, response in self.data["responses"].items():
            if status.startswith("2"):
                return "text/csv" in response.get("content", {})
        return False

    @property
    def body_model(self) -> str | None:
        content = self.data.get("requestBody", {}).get("content", {})
        if not content or self.csv_body:
            return None
        if "application/json" not in content:
            raise SystemExit(f"{self.id}: only JSON request bodies are supported by the generator")
        name = schema_name(content["application/json"]["schema"])
        if name is None:
            raise SystemExit(f"{self.id}: the request body must be a named schema")
        return name

    @property
    def response_model(self) -> str | None:
        for status, response in self.data["responses"].items():
            if status.startswith("2"):
                content = response.get("content", {}).get("application/json")
                return schema_name(content["schema"]) if content else None
        return None


def render_method(op: Operation) -> str:
    lines: list[str] = []
    signature = ["self", "creds: Credentials"]
    path_params = op.parameters("path")
    for param in path_params:
        signature.append(f"{snake(param['name'])}: str")
    keyword_only: list[str] = []
    if op.body_model:
        keyword_only.append(f"body: models.{op.body_model}")
    if op.csv_body:
        keyword_only.append("csv: str")
    queries = op.parameters("query")
    queries.sort(key=lambda p: not p.get("required", False))
    for param in queries:
        py = scalar_type(param["schema"])
        name = snake(param["name"])
        if param.get("required"):
            keyword_only.append(f"{name}: {py}")
        else:
            keyword_only.append(f"{name}: {py} | None = None")
    headers = {p["name"].lower(): p for p in op.parameters("header")}
    if "if-match" in headers:
        keyword_only.append("if_match: int | None = None")
    if keyword_only:
        signature += ["*", *keyword_only]
    if op.csv_response:
        returns = "str"
    else:
        returns = f"models.{op.response_model}" if op.response_model else "None"
    lines.append(f"    async def {op.id}({', '.join(signature)}) -> {returns}:")
    summary = op.data.get("summary", op.id).replace('"""', "'''")
    lines.append(f'        """{summary}"""')
    path_expr = op.path
    for param in path_params:
        path_expr = path_expr.replace("{" + param["name"] + "}", "{" + snake(param["name"]) + "}")
    prefix = "f" if "{" in path_expr else ""
    call = [f'            "{op.method}"', f'            {prefix}"{path_expr}"', "            creds"]
    if op.body_model:
        call.append("            body=body")
    if op.csv_body:
        call.append("            text=csv")
    if queries:
        pairs = ", ".join(f'"{p["name"]}": {snake(p["name"])}' for p in queries)
        call.append(f"            query={{{pairs}}}")
    if "if-match" in headers:
        call.append("            if_match=if_match")
    if op.response_model:
        call.append(f"            response=models.{op.response_model}")
    joined = ",\n".join(call)
    if op.csv_response:
        verb = "return await self._fetch_text"
    elif op.response_model:
        verb = "return await self._fetch"
    else:
        verb = "await self._call"
    lines.append(f"        {verb}(\n{joined},\n        )")
    return "\n".join(lines)


def generate_api(spec: dict[str, Any]) -> str:
    operations = sorted(
        (
            Operation(method, path, data)
            for path, item in spec["paths"].items()
            for method, data in item.items()
            if method in METHODS
        ),
        key=lambda op: op.id,
    )
    body = "\n\n".join(render_method(op) for op in operations)
    permissions = {op.id: op.data.get("x-permission", "") for op in operations}
    table = ",\n".join(f'    "{name}": "{perm}"' for name, perm in permissions.items())
    return (
        HEADER.format(what="One typed method per operation of the API.")
        + "\nfrom __future__ import annotations\n\n"
        + "from datetime import date, datetime  # noqa: F401\n\n"
        + "from planner_client import models\n"
        + "from planner_client.base import ClientBase, Credentials\n\n"
        + f"PERMISSIONS: dict[str, str] = {{\n{table},\n}}\n"
        + '"""Permission of each operation; ``public`` and ``authenticated`` need none."""\n\n\n'
        + "class PlannerApi(ClientBase):\n"
        + body
        + "\n"
    )


def build(target: Path) -> None:
    target.mkdir(parents=True, exist_ok=True)
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    models = target / "models.py"
    generate_models(SPEC, models)
    text = models.read_text(encoding="utf-8")
    models.write_text(
        HEADER.format(what="Request and response models.") + "\n" + text.lstrip(),
        encoding="utf-8",
        newline="\n",
    )
    api = target / "api.py"
    api.write_text(generate_api(spec), encoding="utf-8", newline="\n")
    subprocess.run([sys.executable, "-m", "ruff", "format", "--quiet", str(api)], check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed files differ")
    args = parser.parse_args()
    if not args.check:
        build(PACKAGE)
        print(f"wrote {PACKAGE}")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        build(Path(tmp))
        stale = [
            name
            for name in ("models.py", "api.py")
            if (Path(tmp) / name).read_text(encoding="utf-8")
            != (PACKAGE / name).read_text(encoding="utf-8")
        ]
    if stale:
        print(f"out of date: {', '.join(stale)}; run scripts/generate_client.py", file=sys.stderr)
        return 1
    print("client is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
